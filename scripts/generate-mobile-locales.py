#!/usr/bin/env python3
"""공용 모바일 언어팩을 Java·Swift 상수로 생성하거나 --check로 일치 여부를 검사한다."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'mobile/shared/locales/messages.json'

def quoted(value):
    return json.dumps(value, ensure_ascii=False)

def generate():
    raw = SOURCE.read_bytes();catalog = json.loads(raw)
    stamp = hashlib.sha256(raw).hexdigest()
    for platform in ('android', 'ios'):
        for source, values in catalog[platform].items():
            assert set(values) == {'en', 'ko', 'zh'}, (platform, source)
            assert all(isinstance(value, str) and not value.startswith('[[ZH]]') for value in values.values())
    java = ['// Generated by scripts/generate-mobile-locales.py; edit mobile/shared/locales/messages.json.',
            '// Source SHA-256: ' + stamp, 'package io.github.try2love.codexbridge;',
            'import java.util.*;', 'final class MobileLocaleData {']
    for lang in ('en', 'ko', 'zh'):
        java += [' static final Map<String,String> '+lang+'=make_'+lang+'();',
                 ' private static Map<String,String> make_'+lang+'(){Map<String,String> values=new LinkedHashMap<>();']
        java += ['  values.put('+quoted(source)+','+quoted(values[lang])+');' for source, values in catalog['android'].items()]
        java += ['  return Collections.unmodifiableMap(values);',' }']
    java += [' private static final Map<String,String> aliases=aliases();',
             ' private static Map<String,String> aliases(){Map<String,String> result=new HashMap<>();for(Map<String,String> pack:Arrays.asList(en,ko,zh))for(Map.Entry<String,String> row:pack.entrySet())if(!result.containsKey(row.getValue()))result.put(row.getValue(),row.getKey());return result;}',
             ' static String normalize(String value){String code=(value==null?Locale.getDefault().getLanguage():value).toLowerCase(Locale.ROOT);return code.startsWith("ko")?"ko":code.startsWith("zh")?"zh":"en";}',
             ' static String text(String value,String language){Map<String,String> pack="ko".equals(normalize(language))?ko:"zh".equals(normalize(language))?zh:en;String key=pack.containsKey(value)?value:aliases.get(value);return key==null?value:pack.getOrDefault(key,value);}',
             '}']
    swift = ['// Generated by scripts/generate-mobile-locales.py; edit mobile/shared/locales/messages.json.',
             '// Source SHA-256: ' + stamp, 'import Foundation', 'enum MobileLocaleData {']
    for lang in ('en', 'ko', 'zh'):
        swift += ['    static let '+lang+': [String: String] = [']
        swift += ['        '+quoted(source)+': '+quoted(values[lang])+',' for source, values in catalog['ios'].items()]
        swift += ['    ]']
    swift += ['    static let aliases: [String: String] = {',
              '        var result: [String: String] = [:]',
              '        for pack in [en, ko, zh] { for (key, value) in pack { if result[value] == nil { result[value] = key } } }',
              '        return result', '    }()',
              '    static func normalize(_ value: String?) -> String {',
              '        let language = (value ?? Locale.preferredLanguages.first ?? "en").lowercased()',
              '        return language.hasPrefix("ko") ? "ko" : language.hasPrefix("zh") ? "zh" : "en"', '    }',
              '    static func text(_ value: String, language: String?) -> String {',
              '        let code = normalize(language)',
              '        let pack = code == "ko" ? ko : code == "zh" ? zh : en',
              '        let key = pack[value] != nil ? value : aliases[value]',
              '        return key.flatMap { pack[$0] } ?? value', '    }', '}']
    return {ROOT / 'mobile/android/src/io/github/try2love/codexbridge/MobileLocaleData.java': '\n'.join(java) + '\n',
            ROOT / 'mobile/ios/BridgePreview/MobileLocaleData.swift': '\n'.join(swift) + '\n'}

def main():
    parser = argparse.ArgumentParser(description=__doc__);parser.add_argument('--check', action='store_true');args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit('Regenerate mobile language packs: ' + str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding='utf-8')
    print('Mobile language packs are synchronized' if args.check else 'Generated Java and Swift language packs')

if __name__ == '__main__':
    main()
